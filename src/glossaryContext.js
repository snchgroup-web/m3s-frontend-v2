export const getGlossaryContextEntry = (termId, language = 'FR') => {
  const entry = GLOSSARY_CONTEXT[termId];
  if (!entry) return null;

  const normalizedLanguage = ['FR', 'DE', 'EN'].includes(language) ? language : 'FR';
  return {
    id: termId,
    version: entry.version,
    status: entry.status || 'validated',
    ...entry.translations[normalizedLanguage]
  };
};

